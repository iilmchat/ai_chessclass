async def seed_rag(session: AsyncSession) -> dict[str, int]:
    from rag.models import RagDocument

    existing = set(
        (await session.execute(select(RagDocument.title_ru))).scalars()
    )
    created = 0
    chunks = 0
    for doc in DOCUMENTS:
        if doc["title"] in existing:
            continue
        result = await ingest_document(
            session,
            title_ru=doc["title"],
            source="seed",
            domain=doc["domain"],
            kind=doc["kind"],
            text=doc["text"],
        )
        created += 1
        chunks += result["chunks"]
    return {"rag_documents": created, "rag_chunks": chunks}
