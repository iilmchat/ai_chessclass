"""Системные шаблоны маршрутов (RU) и версии промптов.

Изменение текста шаблона — отдельный коммит с поднятием версии в
PROMPT_VERSIONS и тестом (порт правила teacher §8.1; идентификаторы — SPEC §6.5).
"""

